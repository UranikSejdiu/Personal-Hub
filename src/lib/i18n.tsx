export type TKey = keyof (typeof dict)["sq"];

const MONTHS_SHORT = [
  "msJan",
  "msFeb",
  "msMar",
  "msApr",
  "msMay",
  "msJun",
  "msJul",
  "msAug",
  "msSep",
  "msOct",
  "msNov",
  "msDec",
] as const;

export function monthLabelShort(lang: Lang, key: string): string {
  const month = Number(key.slice(5, 7));
  if (!Number.isInteger(month) || month < 1 || month > 12) return key;
  const year = key.slice(0, 4);
  return `${dict[lang][MONTHS_SHORT[month - 1]]} ${year}`;
}

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = SecureStore.getItem(LANG_KEY);
    if (stored === "en" || stored === "sq") return stored;
    return DEFAULT_LANG;
  });

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    SecureStore.setItem(LANG_KEY, next);
  }, []);

  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>): string => {
      let text: string =
        (dict[lang][key] ?? dict[DEFAULT_LANG][key] ?? key) as string;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replaceAll(`{${k}}`, String(v));
        }
      }
      return text;
    },
    [lang]
  );

  const value = useMemo(
    () => ({ lang, setLang, t }),
    [lang, setLang, t]
  );

  return (
    <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within an I18nProvider.");
  return ctx;
}
