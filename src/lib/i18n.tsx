export type TKey = keyof (typeof dict)["en"];

const MONTHS_SHORT = [
  "msJan",
  "msFeb",
  "msMar",
  "msApr",
  "msMay",
  "msJun",
  "msJul",
  "msAug",
  "msSep",
  "msOct",
  "msNov",
  "msDec",
] as const;

export function monthLabelShort(lang: Lang, key: string): string {
  const month = Number(key.slice(5, 7));
  if (!Number.isInteger(month) || month < 1 || month > 12) return key;
  const year = key.slice(0, 4);
  return `${dict.en[MONTHS_SHORT[month - 1]]} ${year}`;
}

interface I18nContextValue {
  lang: Lang;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>): string => {
      let text: string = dict.en[key];
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replaceAll(`{${k}}`, String(v));
        }
      }
      return text;
    },
    []
  );

  const value = useMemo(
    () => ({ lang: DEFAULT_LANG, t }),
    [t]
  );

  return (
    <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within an I18nProvider.");
  return ctx;
}
