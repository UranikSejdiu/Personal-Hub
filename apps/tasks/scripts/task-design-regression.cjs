const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async function verifyDesign(root, db, tasks, backup, load) {
  const previous = await backup.buildBackupEnvelope();
  const calendar = load(path.join(root, 'src/lib/taskCalendar.ts'));
  try {
    const empty = structuredClone(previous);
    empty.tables.tasks = []; empty.tables.taskLists = [];
    await backup.importBackup(JSON.stringify(empty));
    await tasks.saveTaskList('Errands');
    const list = (await tasks.loadTaskLists()).find(list => list.name === 'Errands');
    const base = { title: 'Today', notes: '', list_id: list.id, due_date: '2030-01-01', priority: 0, repeat: 'none', reminder_time: null };
    const late = await tasks.saveTask({ ...base, title: 'Dentist', due_date: '2029-12-31', reminder_time: '09:00' });
    const timed = await tasks.saveTask({ ...base, title: 'Design review', priority: 2, reminder_time: '10:30' });
    const untimed = await tasks.saveTask({ ...base, title: 'Any time today' });
    await tasks.saveTask({ ...base, title: 'Tomorrow', due_date: '2030-01-02' });
    const inbox = await tasks.saveTask({ ...base, title: '100% literal _ text', due_date: null, list_id: null });
    assert.deepEqual(JSON.parse(JSON.stringify(await tasks.loadTaskOverview('2030-01-01'))), { today: 2, overdue: 1, upcoming: 1, completed: 0, open: 5 });
    const focus = await tasks.loadTasksPage({ filter: 'today', today: '2030-01-01', listId: list.id });
    assert.deepEqual(focus.tasks.map(task => task.id), [late, timed, untimed], 'Overdue stays visible; timed rows precede untimed tasks');
    assert.equal((await tasks.loadTasksPage({ filter: 'overdue', today: '2030-01-01' })).tasks.length, 1);
    assert.equal((await tasks.loadTasksPage({ filter: 'upcoming', today: '2030-01-01' })).tasks.length, 1);
    assert.deepEqual((await tasks.loadTasksPage({ filter: 'active', today: '2030-01-01', listId: null })).tasks.map(task => task.id), [inbox]);
    assert.equal((await tasks.loadTasksPage({ filter: 'active', today: '2030-01-01', date: '2030-01-01' })).tasks.length, 2);
    assert.equal((await tasks.loadTasksPage({ filter: 'active', today: '2030-01-01', search: 'Errands' })).tasks.length, 4, 'Search includes list names');
    assert.deepEqual((await tasks.loadTasksPage({ filter: 'active', today: '2030-01-01', search: '100% literal _' })).tasks.map(task => task.id), [inbox], 'SQL wildcard input stays literal');
    const first = await tasks.loadTasksPage({ filter: 'active', today: '2030-01-01', limit: 2 });
    const second = await tasks.loadTasksPage({ filter: 'active', today: '2030-01-01', limit: 2, offset: first.nextOffset });
    assert.equal(first.hasMore, true); assert.equal(new Set([...first.tasks, ...second.tasks].map(task => task.id)).size, 4);
    assert.deepEqual(await tasks.loadTaskDayCounts('2029-12-31', '2030-01-31'), { '2029-12-31': 1, '2030-01-01': 2, '2030-01-02': 1 });
    const plan = await db.query("EXPLAIN QUERY PLAN SELECT due_date, COUNT(*) FROM tasks WHERE completed_at IS NULL AND due_date >= ? AND due_date <= ? GROUP BY due_date", ['2030-01-01', '2030-01-31']);
    assert.ok(plan.some(row => /idx_tasks_due/.test(row.detail)), 'Calendar markers use the existing due-date index');
    await assert.rejects(tasks.loadTasksPage({ filter: 'active', today: '2030-01-01', listId: -1 }));
    await assert.rejects(tasks.loadTasksPage({ filter: 'active', today: '2030-01-01', date: 'bad' }));
    await tasks.completeTask(timed);
    assert.equal((await tasks.loadTaskOverview('2030-01-01')).completed, 1);
    assert.equal((await tasks.loadTasksPage({ filter: 'all', today: '2030-01-01', date: '2030-01-01' })).tasks.length, 2, 'Calendar can reveal completed tasks');
    await tasks.reopenTask(timed);
    const recurring = await tasks.saveTask({ ...base, title: 'Month end', due_date: '2028-01-31', repeat: 'monthly', reminder_time: '09:00' });
    await tasks.completeTask(recurring);
    let child = await db.get('SELECT * FROM tasks WHERE parent_id = ?', [recurring]);
    assert.equal(child.due_date, '2028-02-29'); assert.equal(child.repeat_day, 31); assert.equal(child.reminder_time, '09:00');
    await tasks.saveTask({ ...child, title: 'Edited next occurrence' }, child.id);
    await assert.rejects(tasks.reopenTask(recurring), tasks.TaskUndoError, 'Undo cannot erase an edited later occurrence');
    await tasks.saveTask({ ...child }, child.id);
    await tasks.reopenTask(recurring);
    assert.equal(await db.get('SELECT id FROM tasks WHERE parent_id = ?', [recurring]), undefined);
    await tasks.completeTask(recurring);
    child = await db.get('SELECT * FROM tasks WHERE parent_id = ?', [recurring]);
    await tasks.saveTaskList('Household', list.id);
    const beforeRemoval = await tasks.loadTask(timed);
    await tasks.deleteTaskList(list.id);
    assert.equal((await tasks.loadTask(timed)).list_id, null);
    assert.equal((await tasks.loadTask(timed)).reminder_time, beforeRemoval.reminder_time);
    assert.equal((await tasks.loadTask(child.id)).parent_id, recurring, 'List deletion preserves repeat chains');
    const exported = await backup.buildBackupEnvelope();
    await backup.importBackup(JSON.stringify(exported));
    assert.deepEqual(JSON.parse(JSON.stringify((await backup.buildBackupEnvelope()).tables)), JSON.parse(JSON.stringify(exported.tables)), 'New UI changes round-trip through the existing backup format');
    const leap = calendar.calendarDays('2028-02-01', '2028-02-29', false);
    assert.equal(leap.length % 7, 0); assert.ok(leap.includes('2028-02-29'));
    assert.equal(calendar.localTaskDate(leap[0]).getDay(), 1, 'Calendar starts on Monday');
    assert.equal(calendar.calendarDays('2028-02-01', '2028-02-29', true).length, 7);
    assert.equal(calendar.moveCalendarDate('2030-12-01', 1, false), '2031-01-01');
    assert.equal(calendar.moveCalendarDate('2030-03-25', 1, true), '2030-04-01', 'Local calendar movement survives daylight-saving boundaries');
    assert.equal(calendar.moveCalendarDate('1000-01-01', -1, false), '1000-01-01');
    assert.equal(calendar.moveCalendarDate('9999-12-01', 1, false), '9999-12-01');
    console.log('Passed Tasks design: aggregate counts, indexed calendar, exact dates, pagination, search, Inbox/list management, recurrence-safe undo, and backup round trips.');
  } finally { await backup.importBackup(JSON.stringify(previous)); }
};
