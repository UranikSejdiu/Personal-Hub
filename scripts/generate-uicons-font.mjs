  Sparkles: "sparkles",
  Star: "star",
  RotateCcw: "rotate-left",
  Pencil: "pencil",
  GripVertical: "grip-vertical",
  ArrowLeft: "arrow-left",
  Pin: "thumbtack",
  PinOff: "thumbtack",
  Bold: "bold",
  Italic: "italic",
  Strikethrough: "strikethrough",
  List: "list",
  ListOrdered: "list-check",
  CheckSquare: "checkbox",
  FileText: "document",
  Search: "search",
  XCircle: "circle-xmark",
  X: "cross-small",
